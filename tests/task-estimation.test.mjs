import assert from 'node:assert/strict';
import { test } from 'node:test';
import { defaultEstimatedMinutes, estimateTaskMinutes } from '../lib/task-estimation.ts';

const scenarios = [
  ['Прочитать главу по истории', 45],
  ['Сделать лабораторную работу по программированию', 120],
  ['Подготовить презентацию', 90],
  ['Написать реферат', 120],
  ['Подготовиться к экзамену', 120],
  ['Решить домашнюю работу', 60],
  ['Купить тетрадь', 60],
  ['Чтение главы', 45],
  ['Законспектировать лекцию', 60],
  ['Сделать ДЗ', 60],
  ['Решить упражнения', 60],
  ['Домашнее задание', 60],
  ['Закончить лабу', 120],
  ['Практическая работа', 90],
  ['Написать эссе', 120],
  ['Подготовить доклад', 120],
  ['Подготовиться к тесту', 60],
  ['Сдать курсовую', 180],
  ['  ПРОЧИТАТЬ\nГЛАВУ!!!  ', 45],
  ['Чтение: повторить всё', 45],
  ['Прочитать главу и подготовиться к экзамену', 120],
  ['Экзамен, презентация, курсовая', 180],
  ['Чтение и конспект', 60],
  ['Домашняя\nработа', 60],
  ['Создать микропрезентацию', 60],
  ['', 60],
  ['   ', 60],
];

for (const [title, minutes] of scenarios) {
  test(`${JSON.stringify(title)} → ${minutes} минут`, () => {
    assert.equal(estimateTaskMinutes(title), minutes);
  });
}

test('Неизвестная задача получает значение по умолчанию', () => {
  assert.equal(estimateTaskMinutes('Купить тетрадь'), defaultEstimatedMinutes);
});

test('Порядок слов и предыдущие вызовы не влияют на максимальную оценку', () => {
  assert.equal(estimateTaskMinutes('Курсовая и презентация'), 180);
  assert.equal(estimateTaskMinutes('Презентация и курсовая'), 180);
  assert.equal(estimateTaskMinutes('Прочитать главу'), 45);
  assert.equal(estimateTaskMinutes('Прочитать главу'), 45);
});

